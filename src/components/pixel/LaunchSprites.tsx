/** Small pixel pictograms for the launch wizard. '#' = color, '+' = dim shade. */
const S: Record<string, string[]> = {
  coreS: ["...##...", "..#++#..", ".#+##+#.", ".#####..", "..#++#..", "...##...", "...##...", "..####.."],
  coreM: ["..####..", ".#+##+#.", "#+#++#+#", "########", "#+#++#+#", ".######.", "...##...", "..####.."],
  coreL: [".#.##.#.", "#+####+#", "#+#++#+#", "########", "#+#++#+#", "########", ".#.##.#.", "#.####.#"],
  Scout: ["........", ".######.", "#+....+#", "#..##..#", "#+....+#", ".######.", "........", "........"],
  Builder: ["######..", "######..", "..##....", "..##....", "..##....", "..##....", "..##....", "..##...."],
  Trader: ["..####..", ".#++++#.", "#+####+#", "#+#++++#", "#++##++#", "#++++#+#", ".#++++#.", "..####.."],
  Diplomat: ["#.......", "######..", "#######.", "######..", "#.......", "#.......", "#.......", "#......."],
  Raider: [".......#", "......#.", ".....#..", "#...#...", ".#.#....", "..#.....", ".#.#....", "#...#..."],
  coins: ["..####..", ".#++++#.", "..####..", ".#++++#.", "..####..", ".#++++#.", "..####..", "........"],
};

export function LaunchSprite({ name, color, scale = 3 }: { name: keyof typeof S | string; color: string; scale?: number }) {
  const rows = S[name] ?? [];
  return (
    <svg width={8 * scale} height={8 * scale} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true">
      {rows.flatMap((row, y) =>
        [...row].map((c, x) =>
          c === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} opacity={c === "+" ? 0.45 : 1} />,
        ),
      )}
    </svg>
  );
}
