GLYPHS["‘"] = ["#.", "#.", ".#"]
SPACE = 4


def outline(rows):
    """Union of filled pixels as clockwise (y-up) loops with collinear points dropped."""
    filled = {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"}
    edges = {}
    for x, r in filled:
        y = CAP - 1 - r
        sq = [(x, y), (x, y + 1), (x + 1, y + 1), (x + 1, y)]
        for a, b in zip(sq, sq[1:] + sq[:1]):
            if (b, a) in edges:
                del edges[(b, a)]
            else:
                edges[(a, b)] = True
    starts = {}
    for a, b in edges:
        starts.setdefault(a, []).append(b)
    loops = []
    while starts:
        a0 = next(iter(starts))
        loop, a = [a0], a0
        prev = None
        while True:
            outs = starts[a]
            if len(outs) > 1 and prev is not None:
                # Turn right at pinch points so diagonal pixels stay separate loops.
                dx, dy = a[0] - prev[0], a[1] - prev[1]
                right = (a[0] + dy, a[1] - dx)
                b = right if right in outs else outs[0]
            else:
                b = outs[0]
            outs.remove(b)
            if not outs:
                del starts[a]
            prev, a = a, b
            if a == a0:
                break
            loop.append(a)
        pts = [p for i, p in enumerate(loop) if not collinear(loop[i - 1], p, loop[(i + 1) % len(loop)])]
        loops.append(pts)
    return loops


def collinear(a, b, c):
    return (b[0] - a[0]) * (c[1] - b[1]) == (b[1] - a[1]) * (c[0] - b[0])


def glyph_name(ch):
    return "space" if ch == " " else f"uni{ord(ch):04X}"


def main():
    names = [".notdef", "space"] + [glyph_name(c) for c in GLYPHS]
    cmap = {32: "space", 0xA0: "space"}
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (5 * PX, 0)
    glyphs["space"] = TTGlyphPen(None).glyph()
    metrics["space"] = (SPACE * PX, 0)
    for ch, rows in GLYPHS.items():
        name = glyph_name(ch)
        cmap[ord(ch)] = name
        if ch.isalpha() and ch.lower() != ch:
            cmap[ord(ch.lower())] = name
        pen = TTGlyphPen(None)
        for loop in outline(rows):
            pen.moveTo((loop[0][0] * PX, loop[0][1] * PX))
            for x, y in loop[1:]:
                pen.lineTo((x * PX, y * PX))
            pen.closePath()
        glyphs[name] = pen.glyph()
        width = max(len(r) for r in rows)
        metrics[name] = ((width + GAP) * PX, 0)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT, lineGap=0)
    fb.setupNameTable({"familyName": "Sovrn Caps", "styleName": "Regular"})
    fb.setupOS2(
        sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
        usWinAscent=ASCENT, usWinDescent=DESCENT, sCapHeight=CAP * PX, sxHeight=CAP * PX,
        fsSelection=0x40,
    )
    fb.setupPost()
    out = Path(__file__).resolve().parents[2] / "public" / "fonts" / "sovrn-caps.woff2"
    fb.font.flavor = "woff2"
    fb.save(out)
    print(f"wrote {out} ({len(GLYPHS)} glyphs)")


if __name__ == "__main__":
    main()
